#!/usr/bin/env python3
"""Generates src/titleui/credits_data.h from AUTHORS and COPYING.NONGPL (run from the repo root)."""
import json, re, sys

H, S, T, B = 0, 1, 2, 3  # heading, section, text, blank

rows = []
import textwrap
def add(style, text=""):
    if style == T and len(text) > 68:
        for part in textwrap.wrap(text, 68):
            rows.append((style, part))
    else:
        rows.append((style, text))

add(H, "Warzone2100 Mobile")
add(T, "A touch-friendly Android adaptation of Warzone 2100.")
add(B)
add(S, "Thank you")
add(T, "This game exists thanks to everyone listed here: the original creators at Pumpkin Studios,")
add(T, "the Warzone 2100 Project team, and every programmer, artist, musician, translator, mapper and tester.")
add(T, "Warzone2100 Mobile is an unofficial adaptation and is not endorsed by the Warzone 2100 Project.")
add(T, "Official project site: wz2100.net")
add(B)
add(S, "Source code")
add(T, "github.com/asdbrg854-netizen/Warzone2100-Mobile")
add(T, "Free software under the GNU GPL: you may study, change and share it.")
add(B)
add(S, "Support the developer")
add(T, "Ko-fi: ko-fi.com/msj5gr")
add(B)
add(S, "Special thanks")
add(T, "Special thanks to Jouri")
add(B)

src = open('AUTHORS', encoding='utf-8').read().splitlines()

def clean(line):
    line = line[2:] if line.startswith('* ') else line
    return line.strip()

# split AUTHORS into blocks by heading
blocks = []   # (kind, title, [entries])
cur = None
i = 0
while i < len(src):
    line = src[i]
    nxt = src[i + 1] if i + 1 < len(src) else ''
    if line.startswith('### '):
        cur = ('section', line[4:].strip(), []); blocks.append(cur)
    elif nxt and set(nxt) <= set('=-') and len(nxt) >= 3 and line.strip():
        if line.strip() == 'Contributors':
            cur = None
        else:
            cur = ('group', line.strip(), []); blocks.append(cur)
        i += 1
    elif line.startswith('* ') and cur is not None:
        cur[2].append(clean(line))
    i += 1

def emit(title):
    for kind, name, entries in blocks:
        if name == title:
            return entries
    return []

# Original authors first
add(S, "Original game: Pumpkin Studios")
for e in emit('Original authors of Warzone 2100 of Pumpkin Studios'):
    add(T, e)
add(B)
add(S, "The Warzone 2100 Project team")
for e in emit('The Warzone 2100 Project team'):
    add(T, e)
add(B)

order = [('Artwork', 'Artwork and designers'), ('Music', 'Music'), ('Maps', 'Maps and map tools'),
         ('Programming', 'Programming'), ('Build systems', 'Build systems'),
         ('Translation', 'Translation'), ('Documentation', 'Documentation'),
         ('Web development', 'Web development'), ('Testing', 'Testing'),
         ('Non-project members whose content has been used in Warzone', 'Content from other contributors')]
for key, title in order:
    entries = emit(key)
    if not entries:
        continue
    add(S, title)
    for e in entries:
        add(T, e)
    add(B)

# Asset licences and third-party code from COPYING.NONGPL
lines = open('COPYING.NONGPL', encoding='utf-8').read().splitlines()
groups = []   # (paths, credits)
paths, credits = [], []
for l in lines[1:]:
    if not l.strip():
        continue
    if l.startswith('\t- ') or l.startswith('\t\t'):
        credits.append(l.strip().lstrip('- ').strip())
    else:
        if credits:
            groups.append((paths, credits)); paths, credits = [], []
        paths.append(l.strip())
if credits:
    groups.append((paths, credits))

add(S, "Assets and third-party software")
add(T, "Used under their own licences:")
seen = set()
for paths, credits in groups:
    for c in credits:
        c = re.sub(r'\s+', ' ', c)
        if c in seen:
            continue
        seen.add(c)
        add(T, c if len(c) < 200 else c[:197] + '...')
add(B)
add(S, "Libraries")
for t in ["SDL - libsdl.org", "OpenGL ES", "Opus / opusfile - opus-codec.org", "libpng, zlib, FreeType, HarfBuzz, PhysFS and others",
          "Built with the Android SDK and NDK"]:
    add(T, t)
add(B)
add(S, "Licence")
add(T, "Warzone 2100 is free software under the GNU General Public License, version 2 or later.")
add(T, "Source code and licence texts are available with this app (COPYING, COPYING.NONGPL, AUTHORS).")
add(B)
add(T, "Thank you for playing.")

out = ['// Generated by platforms/android/tools_gen_credits.py from AUTHORS and COPYING.NONGPL. Do not edit by hand.',
       '#pragma once', '',
       'struct CreditLine { int style; const char *text; }; // style: 0 heading, 1 section, 2 text, 3 blank', '',
       'static const CreditLine kCreditLines[] = {']
for st, tx in rows:
    out.append('\t{%d, %s},' % (st, json.dumps(tx, ensure_ascii=False)))
out.append('};')
open('src/titleui/credits_data.h', 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print(len(rows), 'lines')
