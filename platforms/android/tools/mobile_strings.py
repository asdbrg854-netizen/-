def for_locale(locale_dir):
    """Return {msgid: translation} for a locale directory name such as 'fr' (empty if none)."""
    import mobile_langs_extra, mobile_langs_new, mobile_langs_new2
    values = TRANSLATIONS.get(locale_dir)
    result = dict(zip(MSGIDS, values)) if values else {}
    extra = mobile_langs_extra.EXTRA.get(locale_dir)
    if extra:
        result.update(dict(zip(EXTRA_IDS, extra)))
    for table in (mobile_langs_new.FULL, mobile_langs_new2.FULL):
        full = table.get(locale_dir)
        if full:
            result.update(dict(zip(MSGIDS + EXTRA_IDS, full)))
    result.update(EXTRA_TRANSLATIONS.get(locale_dir, {}))
    return result
