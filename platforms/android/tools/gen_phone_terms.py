#!/usr/bin/env python3
"""Generate lib/framework/i18n_phone_terms.inc: phone wording (tap / long-press / touch) for English UI
strings that talk about the mouse, clicks or function keys. Used on Android only when no translation exists.

Usage (repository root):  python3 platforms/android/tools/gen_phone_terms.py
Reads po/warzone2100.pot, writes lib/framework/i18n_phone_terms.inc
"""
import os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
POT = os.path.join(ROOT, 'po', 'warzone2100.pot')
OUT = os.path.join(ROOT, 'lib', 'framework', 'i18n_phone_terms.inc')

# Hand-written replacements for strings where mechanical rules read badly
EXACT = {
    'Mouse': 'Touch',
    'Mouse Rotate': 'Touch Rotate',
    'Mouse Pan': 'Touch Pan',
    'Right-Click Orders': 'Long-Press Orders',
    'Desktop Full': 'Full Screen',
    'Click/Tap': 'Tap',
    'Right-Click': 'Long-Press',
    'Click/Tap and Hold': 'Tap and Hold',
    'Move the pointer over the artifact and left click to recover it': 'Tap the artifact to recover it',
    'Tutorial is over. Press Esc or the gear icon to quit to the main menu.': 'Tutorial is over. Tap the gear icon to quit to the main menu.',
    '(Press ESC to quit.)': '(Press Back to quit.)',
    'Use left-click for both selection and ordering / targeting. (The classic Warzone 2100 default.)':
        'Tap to both select and order / target. (The classic Warzone 2100 default.)',
    'Order units to move or target with right-click. Select units with left-click. (Matches other common RTS game defaults.)':
        'Order units to move or target with a long-press. Select units with a tap. (Matches other common RTS game defaults.)',
    'By default, Warzone 2100 uses left-click for both selection and ordering / targeting. If you prefer modern RTS mouse input, set this to On. If you are using a trackpad or touch input, you may want to set this to Off.':
        'By default, Warzone 2100 uses a tap for both selection and ordering / targeting. If you prefer modern RTS-style controls, set this to On: a long-press then gives orders and a tap only selects. Otherwise leave it Off.',
    'Center Camera on this Group by clicking or tapping twice': 'Center Camera on this Group by tapping twice',
    'Center Camera on a Group by clicking or tapping twice on the group button': 'Center Camera on a Group by tapping twice on the group button',
}

def case_like(src, word):
    return word[0].upper() + word[1:] if src[0].isupper() else word

def transform(s):
    if s in EXACT:
        return EXACT[s]
    t = s
    t = re.sub(r'\s*\(F\d{1,2}\)', '', t)                                   # "(F1)" function-key hints
    t = re.sub(r'\b[Ll]eft[ -][Cc]lick(?:ing)?\b', lambda m: case_like(m.group(0), 'tapping' if m.group(0).lower().endswith('ing') else 'tap'), t)
    t = re.sub(r'\b[Rr]ight[ -][Cc]lick(?:ing)?\b', lambda m: case_like(m.group(0), 'long-pressing' if m.group(0).lower().endswith('ing') else 'long-press'), t)
    t = re.sub(r'\b([Cc])lick to\b', lambda m: 'Tap to' if m.group(1) == 'C' else 'tap to', t)
    t = re.sub(r'\b([Cc])lick when\b', lambda m: 'Tap when' if m.group(1) == 'C' else 'tap when', t)
    t = re.sub(r'\b([Cc])lick where\b', lambda m: 'Tap where' if m.group(1) == 'C' else 'tap where', t)
    t = re.sub(r'\b([Cc])lick this link\b', lambda m: 'Tap this link' if m.group(1) == 'C' else 'tap this link', t)
    t = re.sub(r'\bclicking this link\b', 'tapping this link', t)
    t = re.sub(r'\bclick the button\b', 'tap the button', t)
    return t

def parse_pot(path):
    text = open(path, encoding='utf-8').read()
    result = []
    for m in re.finditer(r'(?:^#.*\n)*^msgid ((?:"(?:[^"\\\n]|\\.)*"\n)+)', text, re.M):
        raw = ''.join(re.findall(r'"((?:[^"\\\n]|\\.)*)"', m.group(1)))
        # unescape PO string
        s = bytes(raw, 'utf-8').decode('unicode_escape').encode('latin-1').decode('utf-8') if '\\' in raw else raw
        if s:
            result.append(s)
    return result

def c_literal(s):
    out = ['"']
    for b in s.encode('utf-8'):
        c = chr(b)
        if c == '"': out.append('\\"')
        elif c == '\\': out.append('\\\\')
        elif c == '\n': out.append('\\n')
        elif c == '\t': out.append('\\t')
        elif b < 0x20 or b >= 0x7f: out.append('\\%03o' % b)
        else: out.append(c)
    out.append('"')
    return ''.join(out)

def main():
    pairs = []
    seen = set()
    for s in parse_pot(POT):
        if s in seen:
            continue
        seen.add(s)
        t = transform(s)
        if t != s:
            pairs.append((s, t))
    pairs.sort()
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('// Generated by platforms/android/tools/gen_phone_terms.py - do not edit by hand.\n')
        f.write('// English msgid -> phone wording (tap / long-press / touch). Used on Android when no translation exists.\n')
        for s, t in pairs:
            f.write('{ %s,\n  %s },\n' % (c_literal(s), c_literal(t)))
    print('%d replacements written to %s' % (len(pairs), OUT))
    if '--show' in sys.argv:
        for s, t in pairs:
            print('-', s[:110].replace('\n', '\\n'))
            print('+', t[:110].replace('\n', '\\n'))

if __name__ == '__main__':
    main()
